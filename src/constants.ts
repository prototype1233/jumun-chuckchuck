/**
 * 카드를 누른 뒤 다음 화면으로 넘어가기까지 기다리는 시간(ms).
 *
 * 자동 타임아웃이 아니라, 누른 것이 제대로 선택됐는지
 * (테두리 + 배경 + 체크 표시) 눈으로 확인할 틈을 주기 위한 연출이다.
 * 화면마다 반응 속도가 다르면 혼란스러우므로 모든 선택 화면이 이 값을 같이 쓴다.
 */
export const AUTO_ADVANCE_MS = 400

/**
 * 읽어 주는 속도 (1 이 보통 속도).
 *
 * 보통 속도는 어르신께 너무 빨라서 한 번에 알아듣기 어렵고, 재촉하는 느낌까지 준다.
 * 0.85 는 '천천히 또박또박' 과 '늘어져서 답답함' 사이에서 고른 값이다.
 * 더 낮추면(0.8 이하) 기계가 늘어지는 소리로 들려 오히려 알아듣기 어려워진다.
 */
export const SPEECH_RATE = 0.85

/** 목소리 높낮이 — 1(보통)을 그대로 쓴다. 올리면 새된 소리, 내리면 웅얼거리는 소리가 된다. */
export const SPEECH_PITCH = 1

/** 소리 크기 — 매장은 시끄러우므로 항상 최대로 둔다. */
export const SPEECH_VOLUME = 1
